from fastapi import FastAPI, Form, UploadFile, File
from fastapi.middleware.cors import CORSMiddleware
import json
import os
import uuid
import random
from datetime import datetime
from groq import Groq
import traceback

app = FastAPI()

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

DB_FILE = "db.json"
GROQ_API_KEY = os.environ.get("GROQ_API_KEY", "gsk_dummy")  # Add a dummy fallback

def load_db():
    if os.path.exists(DB_FILE):
        with open(DB_FILE, "r") as f:
            try:
                return json.load(f)
            except:
                pass
    return {"users": {}, "history": {}, "reports": {}}

def save_db(db):
    with open(DB_FILE, "w") as f:
        json.dump(db, f, indent=4)

@app.post("/api/auth/login")
async def login(email: str = Form(...), password: str = Form(...)):
    db = load_db()
    # Simple auth stub: if email doesn't exist, create 'New User'
    user_id = email
    if user_id not in db["users"]:
        db["users"][user_id] = {
            "id": user_id,
            "name": "New User",
            "age": 0,
            "gender": "Other",
            "history": ""
        }
        save_db(db)
    
    return {"user": db["users"][user_id]}

@app.post("/api/user/update")
async def update_user(
    user_id: str = Form(...), 
    name: str = Form(...), 
    age: int = Form(...), 
    gender: str = Form(...), 
    history: str = Form("")
):
    db = load_db()
    if user_id in db["users"]:
        db["users"][user_id].update({
            "name": name,
            "age": age,
            "gender": gender,
            "history": history
        })
        save_db(db)
    return {"status": "success"}

