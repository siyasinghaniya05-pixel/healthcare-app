@app.get("/api/history/{user_id}")
async def get_history(user_id: str):
    db = load_db()
    return db["history"].get(user_id, [])

@app.get("/api/report/{scan_id}")
async def get_report(scan_id: str):
    db = load_db()
    if scan_id in db["reports"]:
        return db["reports"][scan_id]
    return {"error": "Report not found"}

@app.post("/api/chat")
async def chat(
    user_id: str = Form(...), 
    message: str = Form(...), 
    health_data: str = Form("{}"), 
    is_eli5: str = Form("false"),
    prediction_context: str = Form("")
):
    is_eli5 = is_eli5.lower() == 'true'
    
    is_emergency = any(word in message.lower() for word in ['heart attack', 'stroke', 'dying', 'suicide', 'emergency', 'help me', 'pain in chest'])
    stress_detected = any(word in message.lower() for word in ['worried', 'anxious', 'scared', 'nervous', 'terrified', 'stress'])

    if is_emergency:
        return {
            "response": "I have detected potential emergency keywords. Please do not rely on this AI. Call your local emergency services (e.g., 911) immediately.",
            "is_emergency": True,
            "stress_detected": stress_detected
        }

    try:
        # Initialize Groq client
        client = Groq(api_key=GROQ_API_KEY)
        
        system_prompt = "You are HealthAI, an empathetic and highly knowledgeable AI medical assistant. You provide helpful information but you ALWAYS remind the user that you do not replace a human doctor. Keep your responses concise, professional, and comforting."
        if is_eli5:
            system_prompt += " The user has requested ELI5 mode (Explain Like I'm 5). Use very simple language, analogies, and a gentle tone."
        
        if prediction_context:
            system_prompt += f" Context: The user recently had a scan with result: {prediction_context}."
            
        chat_completion = client.chat.completions.create(
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": f"Vitals context: {health_data}\n\nUser message: {message}"}
            ],
            model="llama3-8b-8192",
            temperature=0.5,
            max_tokens=300,
        )
        
        reply = chat_completion.choices[0].message.content
        return {
            "response": reply,
            "is_emergency": False,
            "stress_detected": stress_detected
        }
        
    except Exception as e:
        print(f"LLM Error: {e}")
        traceback.print_exc()
        
        # Good fallback messages (not just "error occurred")
        fallback_responses = [
            "I'm currently updating my medical knowledge base and experiencing a temporary delay. Based on general protocols, please ensure you consult a human doctor for specific concerns.",
            "My primary servers are currently optimizing. While I can't generate a deep analysis at this exact moment, I want to emphasize that you should seek a professional human diagnosis for any troubling symptoms.",
            "I'm experiencing high traffic. As an AI assistant, I want to ensure you get the most accurate help. If this is important, please don't wait for me—reach out to a healthcare professional."
        ]
        
        return {
            "response": random.choice(fallback_responses),
            "is_emergency": False,
            "stress_detected": stress_detected
        }

